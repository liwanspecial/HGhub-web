import assert from 'node:assert/strict';
import { build } from 'esbuild';
const output=await build({entryPoints:['src/libraryState.ts'],bundle:true,platform:'node',format:'esm',write:false});
const { normalizeHistory, snapshotVideo, rememberVideo, readView }=await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString('base64')}`);
const legacy=normalizeHistory([123])[0];
assert.deepEqual(legacy,{id:123,ep:1,t:0,dur:0,at:legacy.at});
const history=normalizeHistory([{id:123,ep:2,t:12,dur:90,at:1},{id:123,ep:1},{id:-1},{id:124,ep:0,t:-2}]);
assert.equal(history.length,2);
assert.equal(history[0].ep,2); assert.equal(history[0].t,12); assert.equal(history[1].ep,1); assert.equal(history[1].t,0);
const raw={id:123,title:'合成连续剧',cover:'',author:{id:77,name:'测试博主',followers:100},episodes:[{ep_num:1,title:'第一集',status:1,duration:90},{ep_num:2,title:'第二集',status:1,duration:90}],episode_count:2,total_episodes:2,video_url:'https://media.example.test/?auth_key=dummy-private',video_key:'dummy-private-key',cdn:{authValue:'dummy-secret'}};
const snapshot=snapshotVideo(raw,100);
assert.equal(snapshot.author.name,'测试博主'); assert.equal(snapshot.episodes.length,2);
assert(!JSON.stringify(snapshot).includes('dummy-private')); assert(!JSON.stringify(snapshot).includes('dummy-secret'));
const library=rememberVideo({},raw,100);
assert.equal(rememberVideo(library,raw,200),library,'Same metadata must not create a render/write loop');
assert.deepEqual(readView(JSON.stringify({tab:'profile',libraryTab:'history',watch:{id:123,ep:2}})),{tab:'profile',libraryTab:'history',watch:{id:123,ep:2}});
assert.equal(readView('{invalid').tab,'home');
assert.equal(readView(JSON.stringify({tab:'unknown',watch:{id:-1,ep:0}})).watch,undefined);
console.log('Library/history/navigation: 14 assertions passed');
